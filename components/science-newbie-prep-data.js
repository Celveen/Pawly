// 将原始待办转为统一任务结构。界面只消费结构化字段，后续可平滑接入品种差异或宠物档案。
export const NEWBIE_PREP_BY_CATEGORY = Object.fromEntries(
  Object.entries(RAW_NEWBIE_PREP_BY_CATEGORY).map(([categoryId, value]) => {
    const extra = NEWBIE_PREP_ENHANCEMENTS[categoryId];
    const structuredSections = Object.fromEntries(NEWBIE_PREP_SECTION_DEFINITIONS.map((section) => {
      const rule = TASK_RULES[section.id];
      return [section.id, value[section.id].map((action, index) => ({
        id: `${categoryId}-${section.id}-${index}`,
        level: rule.levels[index] || 'should',
        action,
        reason: rule.reason,
        done: rule.done,
      }))];
    }));
    return [categoryId, { ...value, ...structuredSections, ...extra }];
  }),
);

